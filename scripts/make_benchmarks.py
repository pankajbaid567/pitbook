#!/usr/bin/env python3
"""Generate BENCHMARKS.md from the raw files in bench/results/. Nothing is typed by hand.

Inputs (newest of each kind is used unless --all is given):
  bench/results/loadgen-*.csv             one row per run (cmd/loadgen)
  bench/results/loadgen-*-recovery.csv    recovery-time rows
  bench/results/crashtest-*.json          cmd/crashtest report
  bench/results/property-*.txt            output of `make prop`
  bench/results/mutation-*.txt            output of scripts/mutation_check.sh
"""
import csv
import glob
import json
import os
import statistics as st
import sys
from collections import defaultdict

R = "bench/results"


def newest(pattern):
    files = sorted(glob.glob(os.path.join(R, pattern)))
    return files[-1] if files else None


def med(xs):
    return st.median(xs) if xs else float("nan")


def fmt_us(v):
    if v != v:
        return "n/a"
    return f"{v/1000:.2f} ms" if v >= 1000 else f"{v:.1f} µs"


def fmt_n(v):
    return f"{v:,.0f}"


def load_csv(path):
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def main():
    out = ["# BENCHMARKS", ""]
    lg = [p for p in sorted(glob.glob(os.path.join(R, "loadgen-*.csv"))) if not p.endswith("-recovery.csv")]
    if not lg and not newest("crashtest-*.json"):
        out.append("No results yet. Run `make bench` and `make crash-test`; this file is generated from `bench/results/`.")
        print("\n".join(out))
        return
    out += [
        "Every number below is generated by `python3 scripts/make_benchmarks.py` from the raw files in `bench/results/`. "
        "Method and what is never claimed: [docs/benchmarks-method.md](docs/benchmarks-method.md). "
        "These are **laptop numbers for a single process**; they say nothing about the free-tier host.",
        "",
    ]
    rows = []
    for p in (lg if "--all" in sys.argv else lg[-1:]):
        rows += load_csv(p)
    if rows:
        r0 = rows[0]
        out += [
            "## Environment",
            "",
            f"- CPU: {r0['cpu']} ({r0['cpus']} logical CPUs), {r0['mem_gib']} GiB RAM, {r0['os']}",
            f"- Go {r0['go']}, GOMAXPROCS={r0['gomaxprocs']}, commit `{r0['commit']}`",
            f"- Conditions: {r0['note']}",
            f"- Source: `{os.path.basename(lg[-1])}` ({len(rows)} runs)",
            "- The machine was a normal working laptop with other applications open (see the load average above), "
            "not a quiet benchmarking host; treat the numbers as indicative.",
            "",
        ]
    # ---- saturation
    sat = defaultdict(list)
    for r in rows:
        if float(r["target_rate"]) == 0:
            sat[(r["mode"], r["workload"])].append(r)
    if sat:
        out += ["## Saturation throughput (closed loop, throughput only)", "",
                "The generator submits as fast as the queue accepts. Latency is meaningless here (the queue is always full) and is not reported.", "",
                "| mode | workload | runs | median commands/s | min | max | avg batch (commands per fsync) |", "|---|---|---|---|---|---|---|"]
        for (m, w), rs in sorted(sat.items()):
            t = [float(r["throughput"]) for r in rs]
            out.append(f"| {m} | {w} | {len(rs)} | **{fmt_n(med(t))}** | {fmt_n(min(t))} | {fmt_n(max(t))} | {med([float(r['avg_batch']) for r in rs]):.0f} |")
        out.append("")
    # ---- open loop
    ol = defaultdict(list)
    for r in rows:
        if float(r["target_rate"]) > 0:
            ol[(r["mode"], r["workload"], float(r["target_rate"]), r["symbols"])].append(r)
    if ol:
        out += ["## Open-loop latency", "",
                "Commands are scheduled at a fixed rate and timed from their *scheduled* time to the durable completion callback, so queueing delay is included (no coordinated omission). "
                "Per configuration: the median across repetitions of each percentile, with the range of p99 in brackets. "
                "`wal-sync` acknowledges only after fsync (group commit), `wal-async` writes to the OS but does not fsync, `engine` has no log at all.", "",
                "| mode | workload | target/s | runs | achieved/s | p50 | p99 [range] | p99.9 | max | dropped | avg batch | allocs/cmd | GC pause/run |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for (m, w, rate, ns), rs in sorted(ol.items(), key=lambda kv: (kv[0][1], kv[0][0], kv[0][2])):
            p99 = [float(r["p99_us"]) for r in rs]
            samples = min(int(r["samples"]) for r in rs)
            p999 = fmt_us(med([float(r["p999_us"]) for r in rs])) if samples >= 10000 else "n/a (few samples)"
            wl = w + (f" x{ns}" if w == "multi" else "")
            out.append(
                f"| {m} | {wl} | {fmt_n(rate)} | {len(rs)} | {fmt_n(med([float(r['throughput']) for r in rs]))} | {fmt_us(med([float(r['p50_us']) for r in rs]))} | "
                f"**{fmt_us(med(p99))}** [{fmt_us(min(p99))} – {fmt_us(max(p99))}] | {p999} | {fmt_us(med([float(r['max_us']) for r in rs]))} | "
                f"{sum(int(r['dropped']) for r in rs)} | {med([float(r['avg_batch']) for r in rs]):.0f} | {med([float(r['allocs_per_cmd']) for r in rs]):.2f} | {med([float(r['gc_pause_ms']) for r in rs]):.1f} ms |")
        out += ["", "`dropped` counts commands refused because the queue was full (overload). A row with drops is overloaded and its latency should not be quoted as a service level.", ""]
    # ---- recovery
    rec_path = newest("loadgen-*-recovery.csv")
    if rec_path:
        rr = load_csv(rec_path)
        out += ["## Recovery time", "", "Time for `engine.Open` to rebuild state after a crash (no final snapshot), from a log of the given size.", "",
                "| variant | commands in log | snapshot used | records replayed | recovery time |", "|---|---|---|---|---|"]
        for r in rr:
            out.append(f"| {r['variant']} | {fmt_n(float(r['commands']))} | {fmt_n(float(r['snapshot_seq']))} | {fmt_n(float(r['replayed']))} | **{float(r['took_ms'])/1000:.2f} s** |")
        out.append("")
    # ---- crash test
    ct = newest("crashtest-*.json")
    if ct:
        j = json.load(open(ct))
        t = j["totals"]
        out += ["## Crash safety (`make crash-test`)", "",
                f"`cmd/crashtest`, report `{os.path.basename(ct)}` ({j['date_utc']}): **{j['runs']} runs, {j['failed_runs']} failed**. "
                f"Each run starts the real `pitbook` binary with a synchronous WAL, drives it with {j['clients']} concurrent HTTP clients, sends SIGKILL after a random "
                f"{j['kill_window_ms'][0]}–{j['kill_window_ms'][1]} ms, restarts it and checks the recovered log against what the clients were told.", "",
                "| check | count |", "|---|---|",
                f"| acknowledged commands found in the recovered log, byte-identical to what was sent | {fmt_n(t['acked_commands'])} |",
                f"| fills seen by clients matched to the fill derived by replaying the log | {fmt_n(t['fills_checked'])} |",
                f"| commands in flight at the kill (no response received) | {fmt_n(t['in_flight_at_kill'])} |",
                f"| of those, already in the log without the client knowing | {fmt_n(t['unacked_but_logged'])} |",
                f"| in-flight commands retried with the same client order id | {fmt_n(t['retried'])} |",
                f"| retries answered *duplicate* (not logged twice) | {fmt_n(t['retry_duplicate'])} |",
                f"| runs where recovery used snapshot + log suffix (the rest replayed the log from sequence 1) | {t['runs_recovered_via_snapshot']} of {j['runs']} |", "",
                f"Environment: Go {j['env']['go']} on {j['env']['os']}/{j['env']['arch']}, {j['env']['cpus']} CPUs. Seeds {j['first_seed']}…{j['first_seed']+j['runs']-1}, "
                "every failing seed can be replayed with `-seed N -runs 1`.", "",
                "**Limits.** SIGKILL tests a *process* crash. The OS page cache survives it, so this does not test power loss or disk failure. "
                "Runs are short (a few hundred commands, a few seconds), so most recoveries replay the log from the start; the snapshot path is exercised in the runs listed above and in unit tests.", ""]
    # ---- machine noise floor (control)
    nf = newest("noisefloor-*.txt")
    if nf:
        out += ["## Machine noise floor (control: `go run ./cmd/noisefloor`)", "",
                "A plain spinning thread, no engine, no I/O, measuring the gaps between consecutive clock reads. Any stall here is the machine (scheduler, other processes, power management), not Pitbook. "
                "Tail latencies in the open-loop table cannot be read as better than this floor allows.", "", "```", open(nf).read().strip(), "```", ""]
    # ---- pure matching service time
    ab = newest("applybench-*.txt")
    if ab:
        ns = [float(l.split()[2]) for l in open(ab) if l.startswith("Benchmark")]
        if ns:
            out += ["## Matching core service time (`go test -bench BenchmarkSteadyMix ./internal/book`)", "",
                    "`Book.Apply` on the `steady`-style random mix, one goroutine, no queue, no log, no scheduler in the path: this is the cleanest number for the cost of matching itself.", "",
                    f"- {len(ns)} runs of 3 s: **{med(ns):.0f} ns per command** (median; range {min(ns):.0f} to {max(ns):.0f} ns), i.e. about {1e9/med(ns)/1e6:.1f} million commands/s per core",
                    "- Allocation: see the `allocs/cmd` column above for the whole pipeline; the book itself allocates about one small object per resting order.", ""]
    # ---- property / mutation
    pr = newest("property-*.txt")
    if pr:
        out += ["## Matching correctness (`make prop`)", "", "```", open(pr).read().strip(), "```", ""]
    mu = newest("mutation-*.txt")
    if mu:
        out += ["## Does the property test catch bugs? (`scripts/mutation_check.sh`)", "", "```", open(mu).read().strip(), "```", ""]
    print("\n".join(out))


main()
