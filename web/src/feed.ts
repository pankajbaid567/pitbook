import { useEffect, useReducer, useRef, useState } from "react";
import { emptyBook, reducer, Msg } from "./state";

export type Mode = "connecting" | "live" | "replay";

interface Feed {
  snapshot: Msg;
  frames: Msg[];
}

export const API: string = (() => {
  const q = new URLSearchParams(location.search).get("api");
  const env = (import.meta as unknown as { env: Record<string, string | undefined> }).env.VITE_API_URL;
  return (q || env || "").replace(/\/$/, "");
})();

const wsURL = (): string => {
  const base = API || location.origin;
  return base.replace(/^http/, "ws") + "/v1/ws";
};

/**
 * Live market data with a recorded fallback. The page never shows an empty
 * screen: if the engine does not answer within 3 s (free-tier instances sleep),
 * a recorded session (generated by cmd/genfeed from the same engine) plays while
 * the real connection keeps retrying.
 */
export function useFeed(symbol: string) {
  const [book, dispatch] = useReducer(reducer, symbol, emptyBook);
  const [mode, setMode] = useState<Mode>("connecting");
  const [downSince, setDownSince] = useState<number | null>(null);
  const [liveSince, setLiveSince] = useState<number | null>(null);
  const wsRef = useRef<WebSocket | null>(null);
  const gapRef = useRef(false);
  gapRef.current = book.gap;

  useEffect(() => {
    let closed = false;
    let retry = 0;
    let replayTimers: number[] = [];
    let feed: Feed | null = null;
    let live = false;
    let connectTimer: number | undefined;
    let retryTimer: number | undefined;

    const stopReplay = () => {
      replayTimers.forEach((t) => clearTimeout(t));
      replayTimers = [];
    };

    const startReplay = async () => {
      if (live || closed || replayTimers.length > 0) return;
      setMode("replay");
      setDownSince((d) => d ?? Date.now());
      try {
        feed ??= (await (await fetch("/feed.json")).json()) as Feed;
      } catch {
        return;
      }
      if (live || closed || !feed) return;
      const play = () => {
        if (live || closed || !feed) return;
        dispatch({ type: "reset", symbol });
        dispatch({ type: "msg", msg: feed.snapshot });
        const t0 = (feed.frames[0] as { ts_ms: number }).ts_ms;
        let last = 0;
        for (const f of feed.frames) {
          const at = (f as { ts_ms: number }).ts_ms - t0;
          last = at;
          replayTimers.push(window.setTimeout(() => dispatch({ type: "msg", msg: f }), at));
        }
        replayTimers.push(window.setTimeout(() => { replayTimers = []; play(); }, last + 1500));
      };
      play();
    };

    const connect = () => {
      if (closed) return;
      const ws = new WebSocket(wsURL());
      wsRef.current = ws;
      window.clearTimeout(connectTimer);
      connectTimer = window.setTimeout(() => { if (ws.readyState !== WebSocket.OPEN) void startReplay(); }, 3000);
      ws.onopen = () => {
        window.clearTimeout(connectTimer);
        live = true;
        retry = 0;
        stopReplay();
        dispatch({ type: "reset", symbol });
        setMode("live");
        setDownSince(null);
        setLiveSince(Date.now());
        ws.send(JSON.stringify({ type: "SUBSCRIBE", symbol, depth: 40 }));
      };
      ws.onmessage = (ev) => {
        try {
          dispatch({ type: "msg", msg: JSON.parse(ev.data as string) as Msg });
        } catch { /* ignore malformed frame */ }
      };
      ws.onclose = () => {
        window.clearTimeout(connectTimer);
        live = false;
        if (closed) return;
        void startReplay();
        retry++;
        retryTimer = window.setTimeout(connect, Math.min(5000, 800 * retry));
      };
      ws.onerror = () => ws.close();
    };

    // Waking a sleeping free-tier instance: any HTTP request does it.
    if (API) fetch(API + "/healthz").catch(() => undefined);
    connect();
    return () => {
      closed = true;
      stopReplay();
      window.clearTimeout(connectTimer);
      window.clearTimeout(retryTimer);
      wsRef.current?.close();
    };
  }, [symbol]);

  // Gap detected: ask the server for a fresh snapshot (protocol rule 2).
  useEffect(() => {
    if (book.gap && wsRef.current?.readyState === WebSocket.OPEN) {
      wsRef.current.send(JSON.stringify({ type: "SNAPSHOT_REQUEST", symbol, depth: 40 }));
    }
  }, [book.gap, symbol]);

  return { book, mode, downSince, liveSince };
}
